package ru.aiforge.riftworld.world;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.Random;
import java.util.concurrent.ConcurrentHashMap;

/**
 * «Тлеющие руины» - the lightweight, naturally generated version of the Ashen Lands + castle for normal play.
 *
 * The wild archipelago is divided into 640-block super-cells; ~70 % of them (outside the city ring and away from the real
 * Ashen Lands) hold one site: a scorched island (R 26..32) with a flattened plateau carrying the ruined chapel template
 * (data/riftworld/structures/ruins/chapel.nbt, generated by tools/rift/gen_chapel.py) and 2-3 perched ember guards, inside a
 * small patch of the Ashen biome (R ~78: burnt neighbouring islands with dead trees, ash plain with lava meanders below,
 * ash-brown haze). Deterministic from fixed seeds - no saved data.
 */
public final class EmberRuins {
    public static final int SUPER = 640, EDGE = 130;
    public static final int TW = 19, TD = 28;                 // chapel template footprint
    public static final double ASH_R = 78;
    private static final long SEED = 0xE3B0C4L;
    /** Guard perches inside the template (from chapel_meta.json): on the roof slopes and the broken wall top. */
    public static final int[][] PERCHES = {{3, 13, 6}, {15, 10, 17}, {3, 13, 19}};

    public static final class Site {
        public final int cx, cz, y, x0, z0;
        public final CityPlan.Island island;
        public final List<CityPlan.Tree> trees = new ArrayList<>();
        public final int guards;

        Site(int cx, int cz, int y, double r, Random rnd) {
            this.cx = cx;
            this.cz = cz;
            this.y = y;
            this.x0 = cx - TW / 2;
            this.z0 = cz - TD / 2;
            this.island = new CityPlan.Island(cx, cz, r, y, r * 0.65 + 10, rnd.nextDouble() * 6.283, rnd.nextDouble() * 6.283,
                    rnd.nextDouble() * 6.283, 6, 0.5);
            this.guards = 2 + rnd.nextInt(2);
            for (int k = 0, tries = 0; k < 7 && tries < 200; ++tries) {
                double a = rnd.nextDouble() * Math.PI * 2, d = 6 + rnd.nextDouble() * r;
                int x = (int) Math.floor(cx + Math.cos(a) * d), z = (int) Math.floor(cz + Math.sin(a) * d);
                if (island.t(x, z) < 0.15 || inFootprint(x, z, 4)) continue;
                boolean ok = true;
                for (CityPlan.Tree t : trees) if (Math.abs(t.x - x) < 5 && Math.abs(t.z - z) < 5) { ok = false; break; }
                if (!ok) continue;
                trees.add(new CityPlan.Tree(x, z, 2, 4 + rnd.nextInt(5), rnd.nextInt(1 << 30)));
                ++k;
            }
        }

        public boolean inFootprint(double x, double z, double margin) {
            return x >= x0 - margin && x < x0 + TW + margin && z >= z0 - margin && z < z0 + TD + margin;
        }

        /** Distance outside the footprint rectangle (0 inside). */
        public double outside(double x, double z) {
            double dx = Math.max(Math.max(x0 - x, 0), x - (x0 + TW - 1));
            double dz = Math.max(Math.max(z0 - z, 0), z - (z0 + TD - 1));
            return Math.hypot(dx, dz);
        }
    }

    private static final ConcurrentHashMap<Long, Optional<Site>> CACHE = new ConcurrentHashMap<>();

    private EmberRuins() {
    }

    public static Site site(int sx, int sz) {
        return CACHE.computeIfAbsent(WildIslands.key(sx, sz), k -> Optional.ofNullable(gen(sx, sz))).orElse(null);
    }

    private static Site gen(int sx, int sz) {
        Random r = new Random(SEED ^ (sx * 734287L + sz * 912931L) * 0x9E3779B97F4A7C15L);
        if (r.nextDouble() > 0.7) return null;
        int cx = sx * SUPER + EDGE + r.nextInt(SUPER - 2 * EDGE), cz = sz * SUPER + EDGE + r.nextInt(SUPER - 2 * EDGE);
        if (Math.hypot(cx, cz) < 520) return null;                                                       // city ring
        if (Math.hypot(cx - AshenLands.CX, cz - AshenLands.CZ) < AshenLands.R + 60 + ASH_R + 40) return null;  // real Ashen Lands
        return new Site(cx, cz, 98 + r.nextInt(18), 26 + r.nextDouble() * 6, r);
    }

    /** The site whose area can reach (x, z), or null. */
    public static Site siteAt(double x, double z) {
        Site s = site(Math.floorDiv((int) Math.floor(x), SUPER), Math.floorDiv((int) Math.floor(z), SUPER));
        if (s == null) return null;
        return Math.abs(x - s.cx) < ASH_R + 40 && Math.abs(z - s.cz) < ASH_R + 40 ? s : null;
    }

    /** Ashen weight of the site patch: 0 outside .. 1 inside, wobbly edge. */
    public static double weight(double x, double z) {
        Site s = siteAt(x, z);
        if (s == null) return 0;
        double d = Math.hypot(x - s.cx, z - s.cz) + (ElisarChunkGenerator.vnoise(x * 0.03, z * 0.03, 83) - 0.5) * 26;
        return Math.max(0, Math.min(1, (ASH_R - d) / 18.0));
    }

    public static boolean inFootprint(double x, double z, double margin) {
        Site s = siteAt(x, z);
        return s != null && s.inFootprint(x, z, margin);
    }

    public static List<CityPlan.Tree> treesNear(int x, int z) {
        Site s = siteAt(x, z);
        if (s == null) return List.of();
        List<CityPlan.Tree> out = new ArrayList<>(2);
        for (CityPlan.Tree t : s.trees) if (Math.abs(x - t.x) <= 4 && Math.abs(z - t.z) <= 4) out.add(t);
        return out;
    }

    /** Nearest site centre to (x, z) within the 3x3 super-cells around it (for /riftruins and the compass). */
    public static Site nearest(double x, double z) {
        int sx = Math.floorDiv((int) Math.floor(x), SUPER), sz = Math.floorDiv((int) Math.floor(z), SUPER);
        Site best = null;
        double bd = Double.MAX_VALUE;
        for (int dx = -2; dx <= 2; ++dx)
            for (int dz = -2; dz <= 2; ++dz) {
                Site s = site(sx + dx, sz + dz);
                if (s == null) continue;
                double d = Math.hypot(s.cx - x, s.cz - z);
                if (d < bd) { bd = d; best = s; }
            }
        return best;
    }
}
