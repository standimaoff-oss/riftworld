#!/usr/bin/env python3
"""
v0.40.0 — модель Пегаса (`riftworld:pegasus`) собрана заново: это КОНЬ С РАСКРЫТЫМИ КРЫЛЬЯМИ.

Почему переписано. В кадре 147 прогонов #396–#423 конь читался плохо:
  * шея шла «лесенкой» вперёд-вверх и выглядела жирафьей;
  * крылья были прижаты к боку плоскими пластинами — сбоку это «доски на спине»;
  * ноги короткие: 1/3 роста вместо 1/2, из-за этого конь был похож на таксу;
  * голова размером с коробку, морда не отделена, глаза не видны;
  * шкура почти белая — на снежном фоне моб сливался с пейзажем.

Что теперь (пропорции настоящего коня):
  * холка 34, верх головы 50 юнитов: ноги 22 юнита (44 % роста), а не 16;
  * корпус: грудь глубже бочки, круп с подъёмом, брюхо отдельным блоком;
  * шея — четыре сегмента по дуге, по ГРЕБНЮ идёт тёмная грива, у головы чёлка;
  * голова: череп, скула, длинная морда вниз-вперёд, тёмный нос с ноздрями, уши торчком,
    по бокам выступают глаза с янтарной радужкой;
  * крылья РАСКРЫТЫ на 2.4 блока: плечо → предплечье → кисть идут вверх-в стороны, от кисти
    назад веером расходятся пять маховых с рваной кромкой, под ними средние перья;
  * масть серая с почти чёрными ногами, гривой и хвостом — читается на снегу и в тумане.

Запуск: python3 tools/rift/gen_v040_pegasus_model.py
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from geo_model_lib import Rig  # noqa: E402
from tex_paint import PEGASUS  # noqa: E402

ATLAS = 256

# ---------------------------------------------------------------- масть (светлая, но контрастная)
COAT = "#C9C1B2"          # тёплая серая шкура
COAT_TOP = "#DED7C9"      # хребет светлее
COAT_LOW = "#9C9384"      # брюхо темнее
POINT = "#433D35"         # «отметины»: низ ног, грива, хвост
POINT_LIGHT = "#6B6357"
FEATHER = "#F2ECE1"       # маховые — почти белые
FEATHER_TIP = "#5A544C"   # тёмные кончики
FEATHER_EDGE = "#B9B1A2"
HOOF = "#211E1B"
EYE = "#E9A93C"           # янтарная радужка
NOSE = "#3A342E"
SADDLE = "#6E2F26"
GOLD = "#D9B24C"

MATS = {
    "coat": (COAT_TOP, COAT_LOW, COAT, COAT_LOW),
    "leg": (COAT, POINT, COAT, POINT),
    "skull": (COAT_TOP, COAT, COAT, COAT_LOW),
    "muzzle": (COAT, COAT_LOW, COAT, COAT_LOW),
    "nose": (NOSE, NOSE, NOSE, NOSE),
    "mane": (POINT_LIGHT, POINT, POINT_LIGHT, POINT),
    "tail": (POINT_LIGHT, POINT, POINT_LIGHT, POINT),
    "hoof": (HOOF, HOOF, HOOF, HOOF),
    "eye": (EYE, EYE, EYE, EYE),
    "saddle": (SADDLE, SADDLE, SADDLE, SADDLE),
    "gold": (GOLD, GOLD, GOLD, GOLD),
    # v0.40.0: перья светлые со ВСЕХ сторон (раньше бока были серыми — сбоку крыло
    # читалось серой плитой); кончики и стержни рисует художник текстуры.
    "feather": (FEATHER, FEATHER, FEATHER, FEATHER_EDGE),
    "feather_tip": (FEATHER, FEATHER, FEATHER, FEATHER_EDGE),
}

SPECK = ["#B5AC9C", "#D6CFC1", "#A79E8E"]


def build():
    """Юнит = 1/16 блока, y=0 — земля под копытами, нос смотрит в −Z."""
    r = Rig(ATLAS)

    # ------------------------------------------------------------------ корпус
    r.bone("body", [0, 26, 0])
    r.cube([-5, 20, -10], [10, 13, 20], "coat", SPECK)    # бочка
    r.cube([-5, 18, -15], [10, 15, 7], "coat", SPECK)     # грудь (глубже бочки)
    r.cube([-5, 21, 10], [10, 12, 7], "coat", SPECK)      # круп
    r.cube([-4, 33, -12], [8, 3, 8], "coat", SPECK)       # холка
    r.cube([-4, 17, -9], [8, 4, 19], "coat", SPECK)       # брюхо
    r.cube([-4, 30, -15], [8, 7, 6], "coat", SPECK)       # стык с шеей

    # седло: подушка, передняя и задняя лука, прошивка, стремена по бокам
    r.cube([-5, 33, -6], [10, 2, 9], "saddle")
    r.cube([-4, 35, -7], [8, 2, 2], "saddle")             # передняя лука
    r.cube([-4, 35, 4], [8, 2, 2], "saddle")              # задняя лука
    r.cube([-5, 33, -3], [10, 1, 1], "gold")              # прошивка
    for sx in (-1, 1):
        x = -6 if sx < 0 else 5
        r.cube([x, 26, -3], [1, 8, 2], "saddle")          # ремень стремени
        r.cube([x - 1 if sx < 0 else x, 24, -4], [2, 2, 4], "gold")   # стремя

    # ------------------------------------------------------------------ шея (дуга вверх-вперёд)
    r.bone("neck", [0, 33, -15], {"axis": "x", "amp": 3.0, "speed": 0.8, "phase": 0.0})
    r.cube([-4, 32, -17], [8, 8, 5], "coat", SPECK)       # основание
    r.cube([-3, 35, -21], [6, 8, 5], "coat", SPECK)       # середина
    r.cube([-3, 37, -24], [6, 7, 4], "coat", SPECK)       # верх
    r.cube([-3, 38, -26], [6, 6, 4], "coat", SPECK)       # затылок
    # грива — по ГРЕБНЮ шеи (тем самым «лесенка» читается как грива, а не как ступени)
    r.cube([-1, 39, -16], [2, 3, 6], "mane")
    r.cube([-1, 42, -20], [2, 3, 6], "mane")
    r.cube([-1, 44, -24], [2, 2, 5], "mane")
    r.cube([-1, 44, -27], [2, 3, 4], "mane")

    # ------------------------------------------------------------------ голова
    r.bone("head", [0, 42, -27], {"axis": "x", "amp": 3.0, "speed": 1.0, "phase": 0.6})
    r.cube([-3, 40, -31], [6, 7, 6], "skull", SPECK)      # череп
    r.cube([-3, 38, -31], [6, 3, 5], "skull", SPECK)      # скула/щека
    r.cube([-2, 37, -36], [4, 6, 5], "muzzle", SPECK)     # морда вниз-вперёд
    r.cube([-2, 36, -38], [4, 3, 2], "nose")              # нос
    r.cube([-1, 35, -37], [2, 1, 3], "nose")              # губа
    r.cube([-3, 47, -30], [2, 3, 2], "coat")              # уши
    r.cube([1, 47, -30], [2, 3, 2], "coat")
    r.cube([-3, 48, -29], [2, 2, 1], "mane")              # кисточки на ушах
    r.cube([1, 48, -29], [2, 2, 1], "mane")
    r.cube([-1, 44, -32], [2, 5, 3], "mane")              # чёлка
    r.cube([-4, 42, -30], [1, 3, 3], "eye")               # глаза выступают по бокам черепа
    r.cube([3, 42, -30], [1, 3, 3], "eye")

    # ------------------------------------------------------------------ ноги (передние / задние)
    for side, sx in (("l", -1), ("r", 1)):
        x = -5 if sx < 0 else 1
        ph = 0.0 if sx < 0 else 1.6
        r.bone(f"leg_f{side}", [x + 2, 22, -11], {"axis": "x", "amp": 11.0, "speed": 2.2, "phase": ph})
        r.cube([x, 12, -12], [4, 11, 4], "leg", SPECK)    # предплечье
        r.cube([x, 9, -12], [4, 4, 4], "leg")             # запястье
        r.cube([x + 1, 3, -11], [3, 7, 3], "leg")         # пясть
        r.cube([x + 1, 2, -12], [3, 2, 4], "leg")         # бабка
        r.cube([x, 0, -13], [4, 3, 5], "hoof")            # копыто
    for side, sx in (("l", -1), ("r", 1)):
        x = -5 if sx < 0 else 1
        ph = 0.4 if sx < 0 else 2.0
        r.bone(f"leg_b{side}", [x + 2, 24, 9], {"axis": "x", "amp": 11.0, "speed": 2.2, "phase": ph})
        r.cube([x, 10, 6], [5, 15, 7], "leg", SPECK)      # бедро
        r.cube([x, 7, 8], [4, 6, 5], "leg")               # скакательный сустав
        r.cube([x + 1, 2, 9], [3, 5, 3], "leg")           # плюсна
        r.cube([x, 0, 8], [4, 3, 5], "hoof")              # копыто

    # ------------------------------------------------------------------ хвост
    r.bone("tail", [0, 30, 17], {"axis": "y", "amp": 7.0, "speed": 1.1, "phase": 0.4})
    r.cube([-2, 27, 16], [4, 6, 4], "tail")
    r.cube([-2, 20, 17], [4, 8, 4], "tail")
    r.cube([-2, 12, 18], [3, 9, 3], "tail")
    r.cube([-2, 5, 19], [3, 8, 3], "tail")

    # ------------------------------------------------------------------ крылья (РАСКРЫТЫ)
    # Крыло = костяная основа (плечо → предплечье → кисть) + ВЕЕР маховых.
    # Маховые не лежат друг на друге «плитой»: у каждого свой шаг по высоте (3 высоты + 1
    # просвет), свой вылет и свой сдвиг по X — сбоку видна рваная кромка, а не доска.
    for side, sx in (("l", 1), ("r", -1)):
        def cb(x, y, z, w, h, d, mat):
            """Коробка крыла: для правого крыла X зеркалится."""
            r.cube([x if sx > 0 else -x - w, y, z], [w, h, d], mat)

        r.bone(f"wing_{side}", [sx * 5, 33, -8],
               {"axis": "z", "amp": sx * -8.0, "speed": 1.3, "phase": 0.0})
        cb(5, 33, -13, 4, 6, 10, "feather_tip")           # плечо
        cb(9, 37, -7, 4, 6, 11, "feather_tip")            # предплечье
        cb(12, 41, 1, 3, 6, 8, "feather_tip")             # кисть
        cb(15, 43, 7, 3, 4, 6, "feather_tip")             # пальцы
        # кроющие перья по верху основы — сглаживают «палку»
        cb(5, 39, -12, 4, 2, 9, "feather")
        cb(9, 43, -6, 4, 2, 10, "feather")
        cb(12, 47, 2, 3, 2, 7, "feather")
        # «подмышка»: два узких пера от плеча к боку — крыло срастается с корпусом
        cb(5, 29, -11, 3, 4, 9, "feather")
        cb(5, 25, -7, 3, 4, 8, "feather_tip")
        # маховые: 4 пера веером от кисти назад, между ними просвет в 1 юнит
        # веер: у каждого пера свой сдвиг назад — передняя кромка идёт по диагонали,
        # кончики образуют дугу (параллельные «жалюзи» из прошлой версии читались как доска)
        # v0.40.0: перья ЛЕЖАТ ВПЛОТНУЮ (высота 3, шаг 3) — просвет в 1 юнит в кадре #424
        # превращал веер в «лестницу»; разделяют их тёмная кайма и разный вылет.
        # вылеты подобраны так, чтобы кончики шли по дуге (32 → 29 → 27 → 25), а не ровной стеной:
        # прямоугольный веер в кадре читался «доской», скошенный — крылом
        for i, (yy, ln, xo, zs) in enumerate(((45, 24, 12, 8), (42, 18, 13, 11),
                                             (39, 15, 12, 12), (36, 11, 13, 14))):
            cb(xo, yy, zs, 2, 3, ln, "feather" if i < 3 else "feather_tip")
        # «большой палец» — короткое перо у кисти, закрывает угол
        cb(15, 46, 11, 3, 2, 6, "feather")
        # нижние (средние) перья: от предплечья вниз-назад, закрывают просвет у бока
        cb(9, 31, 3, 3, 5, 12, "feather")
        cb(9, 27, 3, 3, 4, 11, "feather_tip")
    return r


def main():
    r = build()
    info = r.write("pegasus", MATS, "textures/entity/pegasus.png", scale_to=1.0, length_axis=1,
                   length_blocks=2.6, scar_color=None, flip_y=False, painters=PEGASUS)
    print(f"костей: {info['bones']}  кубоидов: {info['cubes']}  render_scale: {info['scale']}")
    print(f"габариты в блоках: {info['size_blocks']} (x, y, z)")
    print("geo:", info["geo"])
    print("tex:", info["tex"])


if __name__ == "__main__":
    main()
